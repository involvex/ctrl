/**
 * Standalone release APK: Gradle assembleRelease embeds the JS bundle.
 * Does not start Metro or open exp+…?__expo_url=… (ports 8081/8082).
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const mobileRoot = join(import.meta.dir, '..');
const repoRoot = join(mobileRoot, '..', '..');
const androidDir = join(mobileRoot, 'android');
if (!existsSync(androidDir)) {
  process.stderr.write(
    'Missing apps/mobile/android. Run: bun run --filter @involvex/ctrl-mobile prebuild:android\n'
  );
  process.exit(1);
}

/**
 * react-native-litert-lm references consumer-rules.pro but does not ship it.
 * Bun reinstalls wipe any copy written during prebuild — recreate before Gradle.
 */
const LITERT_CONSUMER_RULES = `# Auto-generated by ctrl android-release
-keep class com.margelo.nitro.** { *; }
-keep class com.margelo.nitro.dev.litert.** { *; }
-keep class dev.litert.** { *; }
-keep class ai.litert.** { *; }
`;

function ensureLitertConsumerRules(): void {
  const dirs: string[] = [];
  const linked = join(
    mobileRoot,
    'node_modules',
    'react-native-litert-lm',
    'android'
  );
  if (existsSync(join(linked, 'build.gradle'))) {
    dirs.push(linked);
  }
  const bunRoot = join(repoRoot, 'node_modules', '.bun');
  if (existsSync(bunRoot)) {
    for (const name of readdirSync(bunRoot)) {
      if (!name.startsWith('react-native-litert-lm@')) {
        continue;
      }
      const dir = join(
        bunRoot,
        name,
        'node_modules',
        'react-native-litert-lm',
        'android'
      );
      if (existsSync(join(dir, 'build.gradle'))) {
        dirs.push(dir);
      }
    }
  }
  for (const dir of dirs) {
    const rulesPath = join(dir, 'consumer-rules.pro');
    if (!existsSync(rulesPath)) {
      mkdirSync(dir, { recursive: true });
      writeFileSync(rulesPath, LITERT_CONSUMER_RULES, 'utf8');
    }
  }
}

ensureLitertConsumerRules();

const isWin = process.platform === 'win32';
const gradle = isWin ? 'gradlew.bat' : './gradlew';
const result = spawnSync(gradle, ['assembleRelease'], {
  cwd: androidDir,
  stdio: 'inherit',
  shell: isWin,
});

process.exit(result.status === null ? 1 : result.status);
