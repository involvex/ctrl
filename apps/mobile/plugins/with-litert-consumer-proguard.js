/**
 * react-native-litert-lm references consumer-rules.pro but does not ship the
 * file (release warning). Create a minimal keep-rules file when missing, and
 * mirror critical keeps into the app ProGuard rules.
 */
const { withDangerousMod } = require('expo/config-plugins');
const fs = require('node:fs');
const path = require('node:path');

const CONSUMER_RULES = `# Auto-generated by ctrl with-litert-consumer-proguard
-keep class com.margelo.nitro.** { *; }
-keep class com.margelo.nitro.dev.litert.** { *; }
-keep class dev.litert.** { *; }
-keep class ai.litert.** { *; }
`;

const APP_KEEP = `
# @generated begin ctrl-litert-proguard
-keep class com.margelo.nitro.** { *; }
-keep class com.margelo.nitro.dev.litert.** { *; }
-keep class dev.litert.** { *; }
-keep class ai.litert.** { *; }
# @generated end ctrl-litert-proguard
`;

function findLitertAndroidDir(projectRoot) {
  const candidates = [
    path.join(projectRoot, 'node_modules', 'react-native-litert-lm', 'android'),
    path.join(
      projectRoot,
      '..',
      '..',
      'node_modules',
      'react-native-litert-lm',
      'android'
    ),
  ];
  for (const dir of candidates) {
    if (fs.existsSync(path.join(dir, 'build.gradle'))) {
      return dir;
    }
  }
  // Bun content-addressed store
  const bunRoot = path.join(projectRoot, '..', '..', 'node_modules', '.bun');
  if (fs.existsSync(bunRoot)) {
    for (const name of fs.readdirSync(bunRoot)) {
      if (!name.startsWith('react-native-litert-lm@')) {
        continue;
      }
      const dir = path.join(
        bunRoot,
        name,
        'node_modules',
        'react-native-litert-lm',
        'android'
      );
      if (fs.existsSync(path.join(dir, 'build.gradle'))) {
        return dir;
      }
    }
  }
  return null;
}

function withLitertConsumerProguard(config) {
  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      const litertAndroid = findLitertAndroidDir(cfg.modRequest.projectRoot);
      if (litertAndroid) {
        const rulesPath = path.join(litertAndroid, 'consumer-rules.pro');
        if (!fs.existsSync(rulesPath)) {
          fs.writeFileSync(rulesPath, CONSUMER_RULES, 'utf8');
        }
      }
      const appRules = path.join(
        cfg.modRequest.platformProjectRoot,
        'app',
        'proguard-rules.pro'
      );
      if (fs.existsSync(appRules)) {
        const contents = fs.readFileSync(appRules, 'utf8');
        if (!contents.includes('ctrl-litert-proguard')) {
          fs.writeFileSync(
            appRules,
            `${contents.trimEnd()}\n${APP_KEEP}\n`,
            'utf8'
          );
        }
      }
      return cfg;
    },
  ]);

  return config;
}

module.exports = withLitertConsumerProguard;
